% -------------------------------------------------------------------------
% GRNN surrogate models [1]: (x, y) -> A and (x, y) -> B, with a
% spread of 2 m (equivalent Gaussian width sigma = spread/1.1774 =
% 1.70 m, i.e. about half the grid spacing of 4.3-4.5 m), which
% controls the smoothness of the interpolation. Note that the
% goodness-of-fit metrics computed on the training points (see
% regression_metrics.m and Table 6 of the paper) certify the
% reproduction of the fitted maps, not the prediction at unseen points.
% -------------------------------------------------------------------------
net_a = newgrnn([x, y].', a.', 2);
a_hat = net_a([x, y].').';                       % Network response on the training points

net_b = newgrnn([x, y].', b.', 2);
b_hat = net_b([x, y].').';                       % Network response on the training points

% -------------------------------------------------------------------------
% Plot: predicted vs fitted parameters (points on the identity line
% indicate a perfect reproduction of the Gamma parameter maps)
% -------------------------------------------------------------------------
fig = figure;
subplot(1, 2, 1);
plot(a, a_hat, '.');
axis equal;
subplot(1, 2, 2);
plot(b, b_hat, '.');
axis equal;
saveas(fig, './figures/gnn_model.fig');
saveas(fig, './figures/gnn_model.png');

% -------------------------------------------------------------------------
% Save the trained networks for the forecasting scripts (m07, m08)
% -------------------------------------------------------------------------
save('./data/grnn_data.mat', 'net_a', 'net_b');
