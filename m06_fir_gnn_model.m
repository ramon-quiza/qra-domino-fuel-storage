% This script builds the data-driven core of the digital twin: two
% Generalized Regression Neural Networks (GRNN) [1] that map any
% position (x, y) of the terrain to the shape (A) and scale (B)
% parameters of the Gamma distribution of the radiation intensity
% fitted in m05. Once trained, the networks allow the probabilistic
% radiation field to be evaluated at arbitrary points, without being
% restricted to the computation grid (see m07 and m08).
% Alternative surrogate models explored during development (multilayer
% feedforward networks trained with Levenberg-Marquardt, and fuzzy
% inference systems generated by FCM clustering) are kept commented out
% for reference.
% -------------------------------------------------------------------------
% References:
%   [1] Specht, D.F. (1991). A general regression neural network. IEEE
%       Transactions on Neural Networks, 2(6), 568-576.
%       https://doi.org/10.1109/72.97934 (GRNN architecture; the only
%       hyperparameter is the spread of the radial basis functions)
% =========================================================================
clear all;                                       % Clear workspace variables
clc;                                             % Clear command window

% -------------------------------------------------------------------------
% Load the Gamma parameter maps fitted in m05:
%   X, Y - grid coordinates [m]
%   A    - Gamma shape parameter at each grid point [-]
%   B    - Gamma scale parameter at each grid point [kW/m2]
% -------------------------------------------------------------------------
load('./data/gamma_data.mat');

% Flatten the grids into column vectors (one training sample per row)
x = reshape(X, numel(X), 1);
y = reshape(Y, numel(Y), 1);
a = reshape(A, numel(A), 1);
b = reshape(B, numel(B), 1);

% -------------------------------------------------------------------------
% Alternative surrogate models (kept for reference, not used)
